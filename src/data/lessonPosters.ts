export const LESSON_POSTERS_LIST = Object.values(LESSON_POSTERS);

/**
 * Helper to get a poster for a lesson ID with intelligent fallback for revision/monthly units
 */
export function getPosterForLesson(lessonId: string): LessonPoster {
  if (LESSON_POSTERS[lessonId]) {
    return LESSON_POSTERS[lessonId];
  }

  // Handle monthly tests / unit revisions
  if (lessonId.startsWith('u1')) return LESSON_POSTERS['u1_l1'];
  if (lessonId.startsWith('u2')) return LESSON_POSTERS['u2_l1'];
  if (lessonId.startsWith('u3')) return LESSON_POSTERS['u3_l1'];
  if (lessonId.startsWith('u4')) return LESSON_POSTERS['u4_l1'];

  return LESSON_POSTERS['u1_l1'];
}
